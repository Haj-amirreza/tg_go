-- Legacy IDs, encrypted text and original JSON bytes are preserved on import.
-- Existing PHP sessions/grants are deliberately not portable: all admins sign in again.
CREATE TABLE roles (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 name varchar(100) NOT NULL UNIQUE,
 permissions text NOT NULL CHECK (jsonb_typeof(permissions::jsonb) = 'array'),
 level smallint NOT NULL DEFAULT 20 CHECK (level BETWEEN 1 AND 99)
);
CREATE TABLE admins (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 username varchar(80) NOT NULL UNIQUE,
 password_hash varchar(255) NOT NULL,
 name varchar(120) NOT NULL,
 role_id bigint NOT NULL REFERENCES roles(id),
 is_super boolean NOT NULL DEFAULT false,
 active boolean NOT NULL DEFAULT true,
 auth_version integer NOT NULL DEFAULT 1 CHECK (auth_version > 0),
 totp_secret text,
 totp_last bigint NOT NULL DEFAULT 0,
 recovery_codes text,
 created_at bigint NOT NULL
);
CREATE UNIQUE INDEX admins_username_folded ON admins(lower(username));
CREATE INDEX admins_role ON admins(role_id);
CREATE TABLE admin_telegram_links (
 admin_id bigint PRIMARY KEY REFERENCES admins(id) ON DELETE CASCADE,
 telegram_id varchar(32) UNIQUE CHECK (telegram_id ~ '^[1-9][0-9]{0,18}$'),
 challenge_hash varchar(64) UNIQUE,
 expires_at bigint,
 linked_at bigint
);
CREATE TABLE settings (name varchar(100) PRIMARY KEY, value text NOT NULL, is_secret boolean NOT NULL DEFAULT false, updated_at bigint NOT NULL);
CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 telegram_id varchar(32) NOT NULL UNIQUE,
 first_name varchar(200) NOT NULL DEFAULT '', last_name varchar(200) NOT NULL DEFAULT '',
 username varchar(100) NOT NULL DEFAULT '', status varchar(20) NOT NULL DEFAULT 'active',
 delivery_blocked boolean NOT NULL DEFAULT false, interactions integer NOT NULL DEFAULT 0,
 tags varchar(500) NOT NULL DEFAULT '', notes text, conversation text,
 created_at bigint NOT NULL, last_seen bigint NOT NULL
);
CREATE INDEX users_status_seen ON users(status,last_seen);
CREATE INDEX users_created ON users(created_at);
CREATE TABLE admin_sessions (
 token_hash varchar(64) PRIMARY KEY,
 admin_id bigint NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
 auth_version integer NOT NULL,
 expires_at bigint NOT NULL, created_at bigint NOT NULL,
 telegram_id varchar(32)
);
CREATE INDEX admin_sessions_expiry ON admin_sessions(expires_at);
CREATE INDEX admin_sessions_admin ON admin_sessions(admin_id);
CREATE TABLE admin_access_grants (
 token_hash varchar(64) PRIMARY KEY,
 admin_id bigint NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
 telegram_id varchar(32) NOT NULL, auth_version integer NOT NULL,
 page varchar(40) NOT NULL, target_query varchar(255) NOT NULL DEFAULT '',
 expires_at bigint NOT NULL, created_at bigint NOT NULL
);
CREATE INDEX admin_grants_expiry ON admin_access_grants(expires_at);
CREATE INDEX admin_grants_admin ON admin_access_grants(admin_id);
CREATE TABLE auth_attempts (bucket varchar(64) PRIMARY KEY, hits integer NOT NULL, expires_at bigint NOT NULL);
CREATE INDEX auth_attempts_expiry ON auth_attempts(expires_at);
CREATE TABLE telegram_login_replays (digest varchar(64) PRIMARY KEY, expires_at bigint NOT NULL);
CREATE INDEX telegram_login_replays_expiry ON telegram_login_replays(expires_at);
CREATE TABLE identity_audit (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 admin_id bigint REFERENCES admins(id) ON DELETE SET NULL,
 action varchar(50) NOT NULL, created_at bigint NOT NULL
);
CREATE INDEX identity_audit_created ON identity_audit(created_at);
